import { build as buildUi } from 'vite';
import { build as bundle } from 'esbuild';
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
await buildUi({ root, configFile: join(root, 'vite.config.ts') });
const files = {};
const mime = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.json': 'application/json; charset=utf-8', '.webmanifest': 'application/manifest+json' };
async function collect(dir, prefix = '') {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    const relative = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) await collect(path, relative);
    else {
      if (!(extname(entry.name) in mime)) throw new Error(`Unsupported asset type: ${entry.name}`);
      files[relative] = { body: await readFile(path, 'utf8'), contentType: mime[extname(entry.name)] };
    }
  }
}
await collect(join(root, 'dist/ui'));
files['/'] = files['/index.html'];
await writeFile(join(root, 'src/assets.generated.ts'), `// Generated by scripts/build.mjs; do not edit.\nexport const ASSETS: Record<string, {body:string;contentType:string}> = ${JSON.stringify(files)};\n`);
await mkdir(join(root, 'dist'), { recursive: true });
await bundle({ entryPoints: [join(root, 'src/worker/index.ts')], outfile: join(root, 'dist/worker.mjs'), bundle: true, format: 'esm', platform: 'browser', target: 'es2023', minify: true, legalComments: 'inline', conditions: ['browser'] });
console.log(`Built UI and Cloudflare Worker with ${Object.keys(files).length} embedded assets.`);
